"""CMHC Open Data sync service.

Fetches affordable-housing data from:
  1. Toronto Open Data CKAN (no auth)
  2. Canada Open Government Portal CKAN (no auth)
  3. Built-in curated dataset — 75+ listings across all 13 provinces/territories

Records are upserted into the local Listing table; each run is logged.
"""

import logging
import uuid
from datetime import UTC, datetime

from sqlalchemy.ext.asyncio import AsyncSession
from sqlmodel import select

from app.config import settings
from app.models import CmhcSyncLog, Listing, ListingStatus

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------


async def run_sync(
    session: AsyncSession,
    *,
    province: str | None = None,
    city: str | None = None,
) -> CmhcSyncLog:
    """Fetch housing data and upsert listings. Returns the sync-log record."""
    source = "cmhc-open-data"
    log = CmhcSyncLog(source=source, started_at=datetime.utcnow())
    session.add(log)

    try:
        records = await _fetch_cmhc_records(province=province, city=city)
        log.records_fetched = len(records)

        created, updated = await _upsert_listings(session, records)
        log.records_created = created
        log.records_updated = updated
        log.status = "success"
    except Exception as exc:
        logger.exception("CMHC sync failed")
        log.status = "error"
        log.error_message = str(exc)[:500]

    log.completed_at = datetime.utcnow()
    await session.commit()
    await session.refresh(log)
    return log


async def get_sync_logs(
    session: AsyncSession,
    *,
    skip: int = 0,
    limit: int = 20,
) -> list[CmhcSyncLog]:
    stmt = (
        select(CmhcSyncLog)
        .order_by(CmhcSyncLog.started_at.desc())  # type: ignore[union-attr]
        .offset(skip)
        .limit(limit)
    )
    result = await session.execute(stmt)
    return list(result.scalars().all())


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------


async def _fetch_cmhc_records(
    *,
    province: str | None = None,
    city: str | None = None,
) -> list[dict]:
    """Fetch housing records from all available sources.

    Priority:
      1. Real CMHC API (if CMHC_API_KEY is set)
      2. Free Canadian open-data CKAN endpoints
      3. Built-in curated fallback dataset (always succeeds)
    """
    if settings.cmhc_api_key:
        import httpx

        params: dict[str, str] = {}
        if province:
            params["province"] = province
        if city:
            params["city"] = city

        async with httpx.AsyncClient(timeout=30) as client:
            resp = await client.get(
                f"{settings.cmhc_api_url}/v1/affordable-housing",
                params=params,
                headers={"x-api-key": settings.cmhc_api_key},
            )
            resp.raise_for_status()
            data = resp.json()

        return [_normalise(r) for r in data.get("results", [])]

    # Try free open-data sources first
    try:
        from app.services.open_data import fetch_all_open_data

        open_records = await fetch_all_open_data(province=province, city=city)
        if open_records:
            logger.info("Open Data pipeline: %d records fetched", len(open_records))
            # Supplement with built-in seed to ensure full national coverage
            seed = _sample_records(province=province, city=city)
            combined = _merge_dedup(open_records, seed)
            return combined
    except Exception as exc:
        logger.warning("Open Data pipeline failed, falling back to seed: %s", exc)

    logger.info("Using built-in seed dataset (%d listings)", len(_SAMPLE_LISTINGS))
    return _sample_records(province=province, city=city)


def _merge_dedup(primary: list[dict], secondary: list[dict]) -> list[dict]:
    """Merge two record lists, deduplicating by title+address+city."""
    seen: set[tuple[str, str, str]] = set()
    result: list[dict] = []
    for rec in primary + secondary:
        key = (rec.get("title", ""), rec.get("address", ""), rec.get("city", ""))
        if key not in seen:
            seen.add(key)
            result.append(rec)
    return result


def _normalise(raw: dict) -> dict:
    """Map CMHC API fields to our Listing schema."""
    return {
        "title": raw.get("project_name", "CMHC Listing"),
        "description": raw.get("description", ""),
        "address": raw.get("address", ""),
        "city": raw.get("city", ""),
        "province": raw.get("province", ""),
        "postal_code": raw.get("postal_code", ""),
        "latitude": raw.get("latitude"),
        "longitude": raw.get("longitude"),
        "rent_amount": float(raw.get("average_rent", 0) or 0),
        "is_rgi": bool(raw.get("is_rgi", False)),
        "bedrooms": int(raw.get("bedrooms", 1) or 1),
        "bathrooms": 1,
        "is_accessible": bool(raw.get("is_accessible", False)),
        "amenities": raw.get("amenities", ""),
        "max_income": raw.get("max_income"),
        "estimated_wait_days": raw.get("estimated_wait_days"),
        "priority_groups": raw.get("priority_groups", ""),
        "source": "cmhc",
        "source_id": raw.get("id", ""),
    }


async def _upsert_listings(
    session: AsyncSession,
    records: list[dict],
) -> tuple[int, int]:
    """Insert new or update existing listings based on title+address+city key.

    Returns (created_count, updated_count).
    """
    created = 0
    updated = 0

    for rec in records:
        # Strip internal-only keys before DB write
        rec_clean = {k: v for k, v in rec.items() if k not in ("source", "source_id")}

        stmt = select(Listing).where(
            Listing.title == rec_clean.get("title", ""),
            Listing.address == rec_clean.get("address", ""),
            Listing.city == rec_clean.get("city", ""),
        )
        result = await session.execute(stmt)
        existing = result.scalar_one_or_none()

        if existing:
            for k, v in rec_clean.items():
                if v is not None and hasattr(existing, k):
                    setattr(existing, k, v)
            updated += 1
        else:
            if not rec_clean.get("rent_amount") or rec_clean["rent_amount"] <= 0:
                rec_clean["rent_amount"] = 1.0
            now = datetime.utcnow().replace(tzinfo=None)  # naive UTC — matches TIMESTAMP WITHOUT TIME ZONE column
            listing = Listing(**rec_clean, status=ListingStatus.active, created_at=now, updated_at=now)
            session.add(listing)
            created += 1

    await session.flush()
    return created, updated


